"""Intervention evidence system (spec v04 §7, §8, §13, §15).

Three propositions are stored and rendered separately and none inherits the
truth of another (§15.7):

1. ``evidence_signal_associated_with_state`` — the disease profiles and the
   species interpretation registry hold this;
2. ``evidence_intervention_changes_signal`` — a microbiome-surrogate outcome;
3. ``evidence_intervention_changes_clinical_outcome`` — a patient outcome.

The registry lives in ``interventions/*.yaml``: exact intervention
identities, studied protocols, PICO evidence assertions (positive, null,
harm and guideline records alike), safety rules (compiled by
:mod:`openbiota.safety`) and compiled *action mappings* that join a trigger
selector to a protocol, its evidence, its counter-evidence, its safety rules
and its confirmation requirements.

The engine (:func:`generate`) follows the §7.7 algorithm: typed triggers
from QC-qualified findings → exact-key binding → population/indication/
confirmation checks → every safety rule → lane + applicability →
transparent, non-ranked output, with ``no_supported_targeted_intervention``
as a first-class successful result. Nothing here computes a treatment score
or a probability of benefit, and no production sentence is generated by a
language model: prose is assembled deterministically from approved records.
"""

