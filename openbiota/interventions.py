_DESIGN_RANK: Final = {
    "guideline": 0, "regulatory_label": 0, "meta_analysis": 1, "systematic_review": 1, "randomized_trial": 2,
    "nonrandomized_study": 3, "observational_study": 4, "case_report": 5, "protocol": 6, "preprint": 6,
    "consensus_statement": 1, "regulatory_safety_communication": 0, "reference_fact_sheet": 1,
}


def _population_text(protocol: Protocol | None) -> str | None:
    if protocol is None:
        return None
    pop = protocol.population
    bits = []
    if pop.get("confirmed_condition"):
        bits.append(f"people with clinically confirmed {pop['confirmed_condition']}")
    if pop.get("age_range_years"):
        lo, hi = pop["age_range_years"]
        bits.append(f"ages {lo}–{hi}")
    if pop.get("sex"):
        bits.append(str(pop["sex"]))
    if pop.get("geography"):
        bits.append(f"in {pop['geography']}")
    if pop.get("n"):
        bits.append(f"n = {pop['n']}")
    return ", ".join(bits) if bits else None


def _applicability(
    mapping: ActionMapping, protocol: Protocol | None, intervention: Intervention | None,
    triggers: Sequence[TriggerRecord], context: Mapping[str, Any], supporting: Sequence[Assertion],
) -> tuple[Applicability, list[str]]:
    app = Applicability()
    notes: list[str] = []
    subject = context.get("subject", {}) if context else {}
    ctx = context.get("context", {}) if context else {}
    confirmed = {str(c).lower() for c in ctx.get("conditions", []) or []}
    self_reported = {str(c).lower() for c in ctx.get("self_reported_conditions", []) or []}

    # target match
    kinds = {t.trigger_type for t in triggers}
    if "clinician_confirmed_condition" in kinds and any(t.confirmation_status == "verified" for t in triggers):
        app.target_match = "exact"
    elif "exact_microbiome_feature" in kinds or "functional_capacity_finding" in kinds:
        app.target_match = "related"
    elif "research_profile_resemblance" in kinds or "ecological_finding" in kinds:
        app.target_match = "indirect"

    # disease confirmation
    required = [c.lower() for c in mapping.confirmation_rule_refs]
    if required:
        if any(c in confirmed for c in required):
            app.disease_confirmation = "confirmed"
        elif any(c in self_reported for c in required):
            app.disease_confirmation = "self_reported"
            notes.append(f"The studied condition ({', '.join(mapping.confirmation_rule_refs)}) is self-reported here, not clinician-confirmed.")
        else:
            app.disease_confirmation = "profile_only"
            notes.append(
                "The study required a clinical diagnosis of "
                + ", ".join(r.replace("_", " ") for r in mapping.confirmation_rule_refs) + "."
            )
            notes.append("This report provides microbiome resemblance or capacity only.")
            notes.append("Clinical eligibility is therefore unconfirmed.")
    else:
        app.disease_confirmation = "absent"

    known = 0
    total = 0
    # age
    total += 1
    age = subject.get("age_years")
    if protocol is not None and protocol.population.get("age_range_years") and age is not None:
        lo, hi = protocol.population["age_range_years"]
        app.age_match = "exact" if lo <= age <= hi else "outside"
        known += 1
        if app.age_match == "outside":
            notes.append(f"Studied ages were {lo}–{hi}; this subject is outside that range.")
    elif age is not None:
        app.age_match = "exact" if age >= 18 else "outside"
        known += 1
    # sex
    total += 1
    sex = subject.get("sex")
    if protocol is not None and protocol.population.get("sex"):
        if sex is None:
            app.sex_match = "unknown"
            notes.append(f"The study enrolled {protocol.population['sex']} participants only; sex is not on file here.")
        else:
            app.sex_match = "exact" if str(protocol.population["sex"]).lower().startswith(str(sex).lower()[:1]) else "outside"
            known += 1
            if app.sex_match == "outside":
                notes.append(f"The study enrolled {protocol.population['sex']} participants only.")
    else:
        app.sex_match = "not_required"
        known += 1
    # population
    total += 1
    if protocol is None:
        app.population_match = "unknown"
    elif app.disease_confirmation == "confirmed" and app.age_match == "exact" and app.sex_match in ("exact", "not_required"):
        app.population_match = "exact"
        known += 1
    elif app.age_match == "outside" or app.sex_match == "outside":
        app.population_match = "outside"
        known += 1
    elif app.disease_confirmation in ("profile_only", "absent") and protocol.population.get("confirmed_condition"):
        app.population_match = "outside" if app.disease_confirmation == "profile_only" else "partial"
        known += 1
    else:
        app.population_match = "partial"
        known += 1
    # medication context
    total += 1
    if "medications" in ctx:
        app.medication_context_match = "exact" if ctx.get("medications") is not None else "unknown"
        known += 1
    # assay
    total += 1
    app.assay_match = "native" if any(t.microbial_context for t in triggers) else "not_applicable"
    known += 1
    # endpoint relevance from the best supporting record
    total += 1
    classes = [a.outcome_class for a in supporting]
    if any(c in ("patient_clinical", "patient_reported", "validated_biomarker") for c in classes):
        app.endpoint_relevance = "clinical"
    elif "microbiome_surrogate" in classes:
        app.endpoint_relevance = "surrogate"
    else:
        app.endpoint_relevance = "mechanistic"
    known += 1
    # protocol identity
    total += 1
    if intervention is not None:
        app.protocol_identity = "exact" if intervention.exact_protocol_reproducibility == "complete" else "partial"
    else:
        app.protocol_identity = "class_only"
    known += 1
    total += 1  # disease confirmation dimension itself
    if app.disease_confirmation in ("confirmed", "self_reported"):
        known += 1
    app.known_dimension_coverage = known / total if total else 0.0
    return app, notes


def _lane_and_replication(supporting: Sequence[Assertion]) -> tuple[str, str, str | None]:
    if not supporting:
        return "none", "none", None
    best = min(supporting, key=lambda a: LANES.index(a.lane) if a.lane in LANES else 99)
    designs = [a.source.get("source_type") for a in supporting]
    strongest = min(designs, key=lambda d: _DESIGN_RANK.get(str(d), 9)) if designs else None
    directions = {a.effect_direction for a in supporting}
    rct_benefit = [a for a in supporting if a.source.get("source_type") == "randomized_trial" and a.effect_direction == "benefit"]
    if "benefit" in directions and ({"null", "harm", "mixed"} & directions):
        replication = "conflicting"
    elif len(rct_benefit) >= 2:
        replication = "replicated"
    elif supporting:
        replication = "single_study"
    else:
        replication = "none"
    return best.lane, replication, str(strongest) if strongest else None


def _against_set(against: Sequence[Assertion]) -> list[str]:
    kinds = {a.against_kind for a in against if a.against_kind}
    return [k for k in AGAINST_ORDER if k in kinds]


def _assertion_json(a: Assertion, protocol: Protocol | None) -> dict[str, Any]:
    return {
        "evidence_assertion_id": a.evidence_assertion_id, "lane": a.lane, "lane_meaning": LANE_MEANING.get(a.lane, ""),
        "against_kind": a.against_kind, "proposition": a.proposition,
        "source_type": a.source.get("source_type"), "publication_status": a.source.get("publication_status", "peer_reviewed"),
        "citation": a.citation, "url": a.url, "design": a.study.get("design"),
        "participants": a.study.get("participants_randomized") or a.study.get("participants"),
        "risk_of_bias": a.study.get("risk_of_bias", "not_assessed"),
        "funding_and_conflicts": a.study.get("funding_and_conflicts"),
        "comparator": a.pico.get("comparator"), "outcome_class": a.outcome_class,
        "outcome": a.pico.get("outcome", {}).get("name"), "timepoint_days": a.pico.get("outcome", {}).get("timepoint_days"),
        "effect_direction": a.effect_direction, "effect": a.pico.get("effect", {}).get("estimate"),
        "guideline_position": a.guideline_position, "summary": a.summary,
        "studied_protocol": None if protocol is None else protocol.dose_text,
    }


def generate(
    registry: Registry,
    triggers: Sequence[TriggerRecord],
    *,
    sample: str,
    context: Mapping[str, Any] | None,
    mode: str = "participant",
) -> list[EvidenceSummary]:
    """§7.7 steps 2–14 for one sample. Output is unranked (registry order)."""
    context = dict(context or {})
    subject = context.setdefault("subject", {})
    subject.setdefault("mode", mode)
    subject.setdefault("age_known", subject.get("age_years") is not None)
    if subject.get("age_years") is not None:
        subject.setdefault("is_minor", float(subject["age_years"]) < 18)
    ctx = context.setdefault("context", {})
    for key in ("medications", "conditions", "self_reported_conditions", "allergies", "symptoms", "external_labs"):
        if key not in ctx or ctx[key] is None:
            ctx[key] = []

    summaries: list[EvidenceSummary] = []
    counter = 0
    for mapping in registry.mappings:
        matched = [t for t in triggers if mapping.trigger_selector.matches(t)]
        if not matched:
            continue
        # §7.7 step 3: microbial triggers need exact body site + namespace
        rejections: list[str] = []
        micro = [t for t in matched if t.microbial_context]
        for t in micro:
            if t.microbial_context and t.microbial_context.get("body_site") != "stool":
                rejections.append(f"{t.trigger_id}: body site {t.microbial_context.get('body_site')} is not stool")
        matched = [t for t in matched if not any(r.startswith(t.trigger_id) for r in rejections)]
        if not matched:
            continue
        counter += 1
        protocol = registry.protocols.get(mapping.intervention_protocol_ref) if mapping.intervention_protocol_ref else None
        intervention = registry.interventions.get(protocol.intervention_id) if protocol else None
        supporting = [registry.assertions[r] for r in mapping.evidence_assertion_refs]
        against = [registry.assertions[r] for r in mapping.against_evidence_assertion_refs]
        lane, replication, strongest = _lane_and_replication(supporting)
        against_set = _against_set(against)
        guideline = "unavailable"
        for a in supporting + against:
            if a.guideline_position != "unavailable":
                guideline = a.guideline_position
                break
        app, notes = _applicability(mapping, protocol, intervention, matched, context, supporting)

        # base display/action from render + confirmation (steps 6, 9)
        render = mapping.render
        if render in ("not_actionable", "no_supported_targeted_intervention") or render == "inform_only" or render == "evidence_only":
            base_display, base_action = "participant_summary", "evidence_only"
        elif render in ("clinician_review", "guideline_route_after_confirmation"):
            base_display = "clinician_only"
            base_action = "discussable_after_confirmation" if app.disease_confirmation == "confirmed" else "evidence_only"
        else:
            base_display, base_action = "evidence_only", "evidence_only"
        if mapping.confirmation_rule_refs and app.disease_confirmation != "confirmed":
            base_action = "evidence_only"
        if intervention is not None and intervention.intervention_class in ("prescription_drug", "fmt_microbiota_product"):
            base_display = "clinician_only"
            if mode == "participant":
                base_display = "evidence_only"
        if app.age_match == "outside" and subject.get("age_years") is not None and float(subject["age_years"]) < 18:
            base_display, base_action = "suppressed", "suppressed"
            rejections.append("subject is a minor: adult-derived intervention content is suppressed (§8.7)")
        if subject.get("age_years") is None and mode == "participant" and intervention is not None:
            # unknown age fails closed for any live-microbe / supplement / drug content
            base_display = "evidence_only"
            base_action = "evidence_only"
            rejections.append("age not on file: content shown as evidence only (§8.7 unknown age fails closed)")

        # step 8: every matching safety rule
        rules = [registry.safety_rules[r] for r in mapping.safety_rule_refs]
        verdict = apply_rules(
            rules, intervention.intervention_class if intervention else "clinical_route", context,
            base_display=base_display, base_action=base_action,
        )
        display_policy, action_status = verdict.display_policy, verdict.action_status
        if mode == "participant" and display_policy == "clinician_only":
            display_policy = "evidence_only"

        # step 12: never a benefit score. participant prose is deterministic.
        dose_shown = bool(mapping.participant_claim_release_ref) and mode != "participant"
        if mode != "participant" and intervention is not None:
            dose_shown = intervention.intervention_class not in ("prescription_drug", "fmt_microbiota_product") or mode == "clinician"
        paragraphs = _participant_paragraphs(
            registry, mapping, render, intervention, protocol, supporting, against, lane, replication, app,
            verdict, display_policy, dose_shown, mode,
        )
        summaries.append(EvidenceSummary(
            summary_id=f"EVIDENCE_SUMMARY_{sample}_{counter:03d}", action_mapping_id=mapping.action_mapping_id,
            title=mapping.title, render=render, trigger_ids=[t.trigger_id for t in matched],
            trigger_displays=[t.display for t in matched],
            intervention_id=intervention.intervention_id if intervention else None,
            intervention_class=intervention.intervention_class if intervention else None,
            intervention_display=intervention.display_name if intervention else None,
            protocol_ref=protocol.protocol_id if protocol else None,
            studied_protocol_text=protocol.dose_text if protocol and dose_shown else (
                "studied protocol on file (not shown in participant mode)" if protocol else None
            ),
            population_text=_population_text(protocol), supporting_evidence_lane=lane,
            strongest_study_design=strongest, guideline_position=guideline,
            outcome_relevance=app.endpoint_relevance, replication=replication, against_evidence=against_set,
            applicability=app, safety=verdict, display_policy=display_policy, action_status=action_status,
            evidence_summary={
                "benefit_assertions": sum(1 for a in supporting if a.effect_direction == "benefit"),
                "null_assertions": sum(1 for a in supporting + against if a.effect_direction == "null"),
                "harm_assertions": sum(1 for a in supporting + against if a.effect_direction == "harm"),
                "conflicting": replication == "conflicting" or "conflicting" in against_set,
                "strongest_study_design": strongest,
            },
            eligibility_explanation=notes, context_note=mapping.context_note, never_say=list(mapping.never_say),
            follow_up_route=mapping.follow_up_route, fmt_status=mapping.fmt_status,
            supporting=[_assertion_json(a, registry.protocols.get(a.protocol_ref) if a.protocol_ref else None) for a in supporting],
            against=[_assertion_json(a, registry.protocols.get(a.protocol_ref) if a.protocol_ref else None) for a in against],
            sources=list(mapping.sources), rejections=rejections, participant_paragraphs=paragraphs, dose_shown=dose_shown,
        ))
    return summaries


def _participant_paragraphs(
    registry: Registry, mapping: ActionMapping, render: str, intervention: Intervention | None,
    protocol: Protocol | None, supporting: Sequence[Assertion], against: Sequence[Assertion],
    lane: str, replication: str, app: Applicability, verdict: SafetyVerdict, display_policy: str,
    dose_shown: bool, mode: str,  # noqa: ARG001 — mode reserved for clinician-only phrasing
) -> list[str]:
    """Deterministic prose from approved records only."""
    out: list[str] = []
    if render == "no_supported_targeted_intervention" or (render == "not_actionable" and not supporting):
        out.append(NO_TARGETED_SENTENCE.format(version=registry.version))
    if mapping.context_note:
        out.append(mapping.context_note)
    if display_policy == "suppressed":
        out.append("Intervention content for this finding is not shown in this report. " + participant_safety_sentence(verdict))
        return out
    if intervention is not None:
        cls = intervention.intervention_class.replace("_", " ")
        lane_text = LANE_MEANING.get(lane, "")
        head = f"Human research evidence on record: {intervention.display_name} ({cls}), lane {lane} — {lane_text}."
        out.append(head)
        for a in supporting:
            s = a.summary or ""
            out.append(f"{s} [{a.citation}]" if s else f"[{a.citation}]")
        if protocol is not None:
            pop = _population_text(protocol)
            if pop:
                out.append(f"Studied population: {pop}. The studied protocol is a source fact, not an instruction for you.")
            if dose_shown:
                out.append(f"Studied protocol (source-reported): {protocol.dose_text}.")
        if intervention.intervention_class == "prescription_drug":
            out.append(PRESCRIPTION_SENTENCE)
        if intervention.intervention_class == "fmt_microbiota_product":
            out.append(FMT_STATUS_SENTENCE)
        if intervention.exact_protocol_reproducibility != "complete":
            out.append("The exact product composition is incompletely reported in the source; it has not been filled in from retail listings.")
    for a in against:
        out.append(f"Evidence against or limiting: {a.summary} [{a.citation}]")
    if app.disease_confirmation == "profile_only" and mapping.confirmation_rule_refs:
        out.append(
            f"This evidence applies to people with clinically confirmed {', '.join(mapping.confirmation_rule_refs).replace('_', ' ')}. "
            "A microbiome resemblance or capacity reading does not establish that diagnosis."
        )
    if replication == "conflicting":
        out.append("The human evidence is conflicting: positive and null or harmful results are shown together and are not averaged.")
    if mapping.follow_up_route:
        out.append(f"Conventional route: {mapping.follow_up_route}")
    if mapping.fmt_status:
        out.append(f"FMT status for this condition: {mapping.fmt_status.replace('_', ' ')}. " + FMT_STATUS_SENTENCE)
    out.append(participant_safety_sentence(verdict))
    out.append("Nothing here is a treatment score, a probability of benefit, or a personalised prescription. Discuss any change with a clinician or registered dietitian.")
    return out


