@dataclass(frozen=True, slots=True)
class TriggerRecord:
    trigger_id: str
    trigger_type: str
    target: str
    direction: str                    # high | low | present | any
    source_record_ref: str
    confirmation_status: str          # verified | self_reported | profile_only | unknown
    level: str | None = None
    level_rank: int | None = None
    microbial_context: dict[str, Any] | None = None
    display: str = ""

    def to_json(self) -> dict[str, Any]:
        return {
            "trigger_id": self.trigger_id, "trigger_type": self.trigger_type, "target": self.target,
            "direction": self.direction, "source_record_ref": self.source_record_ref,
            "confirmation_status": self.confirmation_status, "level": self.level,
            "microbial_context": self.microbial_context, "display": self.display,
        }


def _rank(level: str | None) -> int | None:
    if level is None:
        return None
    return LEVEL_RANK.get(str(level).lower().replace(" ", "_"))


def _level_words(level: str | None, *, absent: str) -> str:
    """``notably_high`` is a band identifier; the page says ``notably high``."""
    return str(level).replace("_", " ") if level else absent


_PROFILE_LABELS: dict[str, str] = {}


def _profile_label(profile: str) -> str:
    """The reader-facing label from ``profiles/<id>.yaml``, falling back to
    the identifier with its underscores removed. ``ckd`` is an identifier;
    the page says ``Chronic kidney disease``."""
    if profile in _PROFILE_LABELS:
        return _PROFILE_LABELS[profile]
    label = profile.replace("_", " ")
    path = Path(__file__).resolve().parent.parent / "profiles" / f"{profile}.yaml"
    try:
        head = yaml.safe_load(path.read_text()) or {}
        raw = str(head.get("label") or "").strip()
        if raw:
            # "Chronic kidney disease — gut pattern" -> "Chronic kidney disease"
            label = raw.split(" \u2014 ")[0].split(" - ")[0].strip()
    except (OSError, yaml.YAMLError):
        pass
    _PROFILE_LABELS[profile] = label
    return label


def materialize_triggers(
    *,
    sample: str,
    panel_levels: Mapping[str, str | None],
    group_levels: Mapping[str, str | None],
    profile_levels: Mapping[str, str | None],
    profile_abstained: Iterable[str] = (),
    taxa_buckets: Mapping[str, str] = (),
    context: Mapping[str, Any] | None = None,
    qc_qualified: bool = True,
    index_levels: Mapping[str, str | None] | None = None,
) -> list[TriggerRecord]:
    """Step 1–2 of §7.7: typed triggers from QC-qualified evidence only.

    Levels are the seven-band percentile labels (``notably_low`` … ``notably_high``).
    Anything but the microbial namespaces comes from the subject context
    (clinician-confirmed conditions, symptoms, external labs).

    ``index_levels`` carries the v4.2 skin-condition families, banded from
    their 0–100 directional pattern index rather than from a percentile. They
    materialise as ``research_profile_resemblance`` triggers under their own
    namespace so a card can never mistake the index for a percentile."""
    out: list[TriggerRecord] = []
    if qc_qualified:
        for panel, level in panel_levels.items():
            rank = _rank(level)
            direction = "high" if rank is not None and rank > 0 else "low" if rank is not None and rank < 0 else "any"
            out.append(TriggerRecord(
                trigger_id=f"TRIGGER_{sample}_PANEL_{panel.upper()}", trigger_type="functional_capacity_finding",
                target=panel, direction=direction, source_record_ref=f"panel:{panel}",
                confirmation_status="profile_only", level=level, level_rank=rank,
                microbial_context={"body_site": "stool", "namespace": "gene_capacity_rpoB_normalised", "direction": direction},
                display=f"{panel.replace('_', ' ')} gene capacity: {_level_words(level, absent='no reference position')}",
            ))
        for group, level in group_levels.items():
            rank = _rank(level)
            direction = "high" if rank is not None and rank > 0 else "low" if rank is not None and rank < 0 else "any"
            out.append(TriggerRecord(
                trigger_id=f"TRIGGER_{sample}_GROUP_{group.upper()}", trigger_type="ecological_finding",
                target=group, direction=direction, source_record_ref=f"group:{group}",
                confirmation_status="profile_only", level=level, level_rank=rank,
                microbial_context={"body_site": "stool", "namespace": "MetaPhlAn3_species_relative", "direction": direction},
                display=f"{group.replace('_', ' ')} relative abundance: {_level_words(level, absent='no reference position')}",
            ))
        abstained = set(profile_abstained)
        for profile, level in profile_levels.items():
            if profile in abstained:
                continue
            rank = _rank(level)
            direction = "high" if rank is not None and rank > 0 else "low" if rank is not None and rank < 0 else "any"
            out.append(TriggerRecord(
                trigger_id=f"TRIGGER_{sample}_PROFILE_{profile.upper()}", trigger_type="research_profile_resemblance",
                target=profile, direction=direction, source_record_ref=f"profile:{profile}",
                confirmation_status="profile_only", level=level, level_rank=rank,
                microbial_context={"body_site": "stool", "namespace": "profile_similarity_percentile", "direction": direction},
                display=f"{_profile_label(profile)} pattern: {_level_words(level, absent='not scored')}",
            ))
        for family, level in dict(index_levels or {}).items():
            rank = _rank(level)
            direction = "high" if rank is not None and rank > 0 else "low" if rank is not None and rank < 0 else "any"
            out.append(TriggerRecord(
                trigger_id=f"TRIGGER_{sample}_INDEX_{family.upper()}", trigger_type="research_profile_resemblance",
                target=family, direction=direction, source_record_ref=f"skin_family:{family}",
                confirmation_status="profile_only", level=level, level_rank=rank,
                microbial_context={"body_site": "stool", "namespace": "directional_pattern_index_0_100", "direction": direction},
                display=f"{family.replace('_', ' ')} stool pattern: {_level_words(level, absent='not scored')}",
            ))
        for species, bucket in dict(taxa_buckets).items():
            direction = (
                "high" if bucket in ("high", "unexpected_present", "concern")
                else "low" if bucket in ("low", "absent_expected")
                else "present"
            )
            out.append(TriggerRecord(
                trigger_id=f"TRIGGER_{sample}_TAXON_{species.upper()}", trigger_type="exact_microbiome_feature",
                target=species, direction=direction,
                source_record_ref=f"taxon:{species}", confirmation_status="profile_only",
                level=bucket, level_rank=None,
                microbial_context={"body_site": "stool", "namespace": "MetaPhlAn3_species_relative", "direction": bucket},
                display=f"{species.replace('_', ' ')}: {bucket.replace('_', ' ')}",
            ))
    ctx = dict(context or {}).get("context", {}) if context else {}
    for cond in ctx.get("conditions", []) or []:
        out.append(TriggerRecord(
            trigger_id=f"TRIGGER_{sample}_CONDITION_{str(cond).upper()}", trigger_type="clinician_confirmed_condition",
            target=str(cond), direction="present", source_record_ref="manifest:context.conditions",
            confirmation_status="verified", display=f"clinician-confirmed {cond}",
        ))
    for cond in ctx.get("self_reported_conditions", []) or []:
        out.append(TriggerRecord(
            trigger_id=f"TRIGGER_{sample}_SELFREPORTED_{str(cond).upper()}", trigger_type="clinician_confirmed_condition",
            target=str(cond), direction="present", source_record_ref="manifest:context.self_reported_conditions",
            confirmation_status="self_reported", display=f"self-reported {cond}",
        ))
    for sym in ctx.get("symptoms", []) or []:
        out.append(TriggerRecord(
            trigger_id=f"TRIGGER_{sample}_SYMPTOM_{str(sym).upper()}", trigger_type="symptom_phenotype",
            target=str(sym), direction="present", source_record_ref="manifest:context.symptoms",
            confirmation_status="self_reported", display=f"reported {sym}",
        ))
    for lab in ctx.get("external_labs", []) or []:
        name = lab.get("name") if isinstance(lab, Mapping) else str(lab)
        out.append(TriggerRecord(
            trigger_id=f"TRIGGER_{sample}_LAB_{str(name).upper()}", trigger_type="external_lab_abnormality",
            target=str(name), direction=str(lab.get("direction", "present")) if isinstance(lab, Mapping) else "present",
            source_record_ref="manifest:context.external_labs", confirmation_status="verified",
            display=f"external lab {name}",
        ))
    return out


