@dataclass(frozen=True, slots=True)
class Intervention:
    intervention_id: str
    version: str
    intervention_class: str
    display_name: str
    identity: dict[str, Any]
    transfer_policy: dict[str, str]
    exact_protocol_reproducibility: str      # complete | incomplete
    regulatory_status: str | None = None
    label_warnings: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class Protocol:
    protocol_id: str
    intervention_id: str
    population: dict[str, Any]
    administration: dict[str, Any]
    studied_protocol_not_personalized_instruction: bool = True

    @property
    def dose_text(self) -> str:
        return str(self.administration.get("dose_source_text") or "dose as studied (see source)")


@dataclass(frozen=True, slots=True)
class Assertion:
    evidence_assertion_id: str
    protocol_ref: str | None
    intervention_ref: str | None
    source: dict[str, Any]
    study: dict[str, Any]
    pico: dict[str, Any]
    lane: str                                # A–E or X
    proposition: str
    against_kind: str | None                 # for lane X: guideline_against | null_primary | harm_signal | conflicting
    target_binding: dict[str, Any]
    summary: str
    guideline_position: str = "unavailable"

    @property
    def effect_direction(self) -> str:
        return str(self.pico.get("effect", {}).get("direction") or "not_estimable")

    @property
    def outcome_class(self) -> str:
        return str(self.pico.get("outcome", {}).get("class") or "mechanistic")

    @property
    def url(self) -> str:
        s = self.source
        if s.get("url"):
            return str(s["url"])
        if s.get("pmid"):
            return f"https://pubmed.ncbi.nlm.nih.gov/{s['pmid']}/"
        if s.get("doi"):
            return f"https://doi.org/{s['doi']}"
        return ""

    @property
    def citation(self) -> str:
        return str(self.source.get("citation") or self.url)


@dataclass(frozen=True, slots=True)
class TriggerSelector:
    trigger_type: str
    target: str                   # profile name / panel name / group name / species / condition / symptom
    direction: str = "any"        # high | low | present | any
    min_level: str | None = None  # for percentile-based triggers: e.g. "elevated" or "notably_high"

    def patterns(self) -> tuple[str, ...]:
        """``{a,b_*}`` alternation on top of fnmatch wildcards."""
        t = self.target.strip()
        if t.startswith("{") and t.endswith("}"):
            return tuple(p.strip() for p in t[1:-1].split(",") if p.strip())
        return (t,)

    def matches(self, trigger: TriggerRecord) -> bool:
        if trigger.trigger_type != self.trigger_type:
            return False
        if not any(fnmatch.fnmatchcase(trigger.target, p) for p in self.patterns()):
            return False
        if self.direction != "any" and trigger.direction != self.direction:
            return False
        if self.min_level is not None and trigger.level_rank is not None:
            return trigger.level_rank >= LEVEL_RANK.get(self.min_level, 0)
        return True


@dataclass(frozen=True, slots=True)
class ActionMapping:
    action_mapping_id: str
    trigger_selector: TriggerSelector
    render: str
    intervention_protocol_ref: str | None
    evidence_assertion_refs: tuple[str, ...]
    against_evidence_assertion_refs: tuple[str, ...]
    safety_rule_refs: tuple[str, ...]
    confirmation_rule_refs: tuple[str, ...]      # conditions that must be clinician-confirmed
    participant_claim_release_ref: str | None
    title: str
    context_note: str
    never_say: tuple[str, ...]
    sources: tuple[dict[str, str], ...]
    follow_up_route: str | None = None
    fmt_status: str | None = None


LEVEL_RANK: Final = {
    "notably_low": -3, "low": -2, "somewhat_low": -1, "typical": 0,
    "somewhat_high": 1, "high": 2, "notably_high": 3, "elevated": 2, "reduced": -2,
}


@dataclass(slots=True)
class Registry:
    version: str
    interventions: dict[str, Intervention]
    protocols: dict[str, Protocol]
    assertions: dict[str, Assertion]
    safety_rules: dict[str, SafetyRule]
    mappings: list[ActionMapping]
    digest: str

    def validate(self) -> list[str]:
        problems: list[str] = []
        for p in self.protocols.values():
            if p.intervention_id not in self.interventions:
                problems.append(f"protocol {p.protocol_id} references unknown intervention {p.intervention_id}")
        for a in self.assertions.values():
            if a.protocol_ref and a.protocol_ref not in self.protocols:
                problems.append(f"assertion {a.evidence_assertion_id} references unknown protocol {a.protocol_ref}")
            if a.intervention_ref and a.intervention_ref not in self.interventions:
                problems.append(f"assertion {a.evidence_assertion_id} references unknown intervention {a.intervention_ref}")
            if a.lane not in LANES:
                problems.append(f"assertion {a.evidence_assertion_id} has lane {a.lane!r}")
            if a.lane == "X" and a.against_kind not in AGAINST_ORDER:
                problems.append(f"assertion {a.evidence_assertion_id} is lane X without a valid against_kind")
            if a.lane != "X" and a.against_kind:
                problems.append(f"assertion {a.evidence_assertion_id} has against_kind but lane {a.lane}")
            if a.proposition not in PROPOSITIONS:
                problems.append(f"assertion {a.evidence_assertion_id} proposition {a.proposition!r}")
            if a.source.get("source_type") not in SOURCE_TYPES:
                problems.append(f"assertion {a.evidence_assertion_id} source_type {a.source.get('source_type')!r}")
            if not (a.source.get("pmid") or a.source.get("doi") or a.source.get("url")):
                problems.append(f"assertion {a.evidence_assertion_id} has no PMID, DOI or URL")
            if a.outcome_class not in OUTCOME_CLASSES:
                problems.append(f"assertion {a.evidence_assertion_id} outcome class {a.outcome_class!r}")
            if a.guideline_position not in GUIDELINE_POSITIONS:
                problems.append(f"assertion {a.evidence_assertion_id} guideline_position {a.guideline_position!r}")
        seen: set[str] = set()
        for m in self.mappings:
            if m.action_mapping_id in seen:
                problems.append(f"duplicate action_mapping_id {m.action_mapping_id}")
            seen.add(m.action_mapping_id)
            if m.render not in RENDERS:
                problems.append(f"mapping {m.action_mapping_id} render {m.render!r}")
            if m.trigger_selector.trigger_type not in TRIGGER_TYPES:
                problems.append(f"mapping {m.action_mapping_id} trigger_type {m.trigger_selector.trigger_type!r}")
            if m.intervention_protocol_ref and m.intervention_protocol_ref not in self.protocols:
                problems.append(f"mapping {m.action_mapping_id} references unknown protocol {m.intervention_protocol_ref}")
            for ref in m.evidence_assertion_refs + m.against_evidence_assertion_refs:
                if ref not in self.assertions:
                    problems.append(f"mapping {m.action_mapping_id} references unknown assertion {ref}")
            for ref in m.against_evidence_assertion_refs:
                if ref in self.assertions and self.assertions[ref].lane != "X":
                    problems.append(f"mapping {m.action_mapping_id}: against-evidence {ref} is not lane X")
            for ref in m.evidence_assertion_refs:
                if ref in self.assertions and self.assertions[ref].lane == "X":
                    problems.append(f"mapping {m.action_mapping_id}: supporting ref {ref} is lane X")
            for ref in m.safety_rule_refs:
                if ref not in self.safety_rules:
                    problems.append(f"mapping {m.action_mapping_id} references unknown safety rule {ref}")
            if m.intervention_protocol_ref:
                iv = self.interventions[self.protocols[m.intervention_protocol_ref].intervention_id]
                if iv.intervention_class in ("prescription_drug", "fmt_microbiota_product") and m.render not in (
                    "clinician_review", "guideline_route_after_confirmation", "evidence_only",
                ):
                    problems.append(f"mapping {m.action_mapping_id}: prescription/FMT must be clinician-review or evidence-only")
                if iv.intervention_class in ("prescription_drug", "fmt_microbiota_product") and not m.confirmation_rule_refs:
                    problems.append(f"mapping {m.action_mapping_id}: prescription/FMT needs a confirmation rule")
        return problems

    def to_lock(self) -> dict[str, Any]:
        return {
            "registry_version": self.version, "digest": self.digest,
            "interventions": len(self.interventions), "protocols": len(self.protocols),
            "assertions": len(self.assertions), "safety_rules": len(self.safety_rules),
            "action_mappings": len(self.mappings),
        }


def _as_tuple(value: Any) -> tuple[str, ...]:
    if value is None:
        return ()
    if isinstance(value, str):
        return (value,)
    return tuple(str(v) for v in value)


def load_registry(directory: Path) -> Registry:
    """Load and validate every YAML file under ``interventions/``."""
    files = sorted(directory.glob("*.yaml"))
    if not files:
        raise OpenBiotaError(f"no intervention registry under {directory}")
    raw: dict[str, list[Any]] = {"interventions": [], "protocols": [], "assertions": [], "safety_rules": [], "action_mappings": []}
    digest = hashlib.sha256()
    for path in files:
        text = path.read_text()
        digest.update(path.name.encode() + text.encode())
        data = yaml.safe_load(text) or {}
        for key in raw:
            raw[key].extend(data.get(key, []) or [])

    interventions: dict[str, Intervention] = {}
    for r in raw["interventions"]:
        cls = r.get("class")
        if cls not in INTERVENTION_CLASSES:
            raise OpenBiotaError(f"intervention {r.get('intervention_id')}: unknown class {cls!r}")
        iv = Intervention(
            intervention_id=r["intervention_id"], version=str(r.get("version", "1.0.0")), intervention_class=cls,
            display_name=r["display_name"], identity=dict(r.get("identity") or {}),
            transfer_policy=dict(r.get("transfer_policy") or {}),
            exact_protocol_reproducibility=str(r.get("exact_protocol_reproducibility", "complete")),
            regulatory_status=r.get("regulatory_status"), label_warnings=_as_tuple(r.get("label_warnings")),
        )
        if iv.intervention_id in interventions:
            raise OpenBiotaError(f"duplicate intervention_id {iv.intervention_id}")
        interventions[iv.intervention_id] = iv

    protocols: dict[str, Protocol] = {}
    for r in raw["protocols"]:
        p = Protocol(
            protocol_id=r["protocol_id"], intervention_id=r["intervention_id"],
            population=dict(r.get("population") or {}), administration=dict(r.get("administration") or {}),
        )
        if p.protocol_id in protocols:
            raise OpenBiotaError(f"duplicate protocol_id {p.protocol_id}")
        protocols[p.protocol_id] = p

    assertions: dict[str, Assertion] = {}
    for r in raw["assertions"]:
        a = Assertion(
            evidence_assertion_id=r["evidence_assertion_id"], protocol_ref=r.get("protocol_ref"),
            intervention_ref=r.get("intervention_ref"), source=dict(r.get("source") or {}),
            study=dict(r.get("study") or {}), pico=dict(r.get("pico") or {}), lane=str(r.get("lane", "")),
            proposition=str(r.get("proposition", "")), against_kind=r.get("against_kind"),
            target_binding=dict(r.get("target_binding") or {}), summary=str(r.get("summary", "")).strip(),
            guideline_position=str(r.get("guideline_position", "unavailable")),
        )
        if a.evidence_assertion_id in assertions:
            raise OpenBiotaError(f"duplicate evidence_assertion_id {a.evidence_assertion_id}")
        assertions[a.evidence_assertion_id] = a

    rules = {r.rule_id: r for r in (compile_rule(x) for x in raw["safety_rules"])}

    mappings: list[ActionMapping] = []
    for r in raw["action_mappings"]:
        sel = r.get("trigger_selector") or {}
        mappings.append(
            ActionMapping(
                action_mapping_id=r["action_mapping_id"],
                trigger_selector=TriggerSelector(
                    trigger_type=sel.get("trigger_type", ""), target=str(sel.get("target", "*")),
                    direction=str(sel.get("direction", "any")), min_level=sel.get("min_level"),
                ),
                render=str(r.get("render", "evidence_only")),
                intervention_protocol_ref=r.get("intervention_protocol_ref"),
                evidence_assertion_refs=_as_tuple(r.get("evidence_assertion_refs")),
                against_evidence_assertion_refs=_as_tuple(r.get("against_evidence_assertion_refs")),
                safety_rule_refs=_as_tuple(r.get("safety_rule_refs")),
                confirmation_rule_refs=_as_tuple(r.get("confirmation_rule_refs")),
                participant_claim_release_ref=r.get("participant_claim_release_ref"),
                title=str(r.get("title", "")), context_note=str(r.get("context_note", "")).strip(),
                never_say=_as_tuple(r.get("never_say")), sources=tuple(dict(s) for s in r.get("sources", []) or []),
                follow_up_route=r.get("follow_up_route"), fmt_status=r.get("fmt_status"),
            )
        )
    reg = Registry(
        version=REGISTRY_VERSION, interventions=interventions, protocols=protocols, assertions=assertions,
        safety_rules=rules, mappings=mappings, digest="sha256:" + digest.hexdigest(),
    )
    problems = reg.validate()
    if problems:
        raise OpenBiotaError("intervention registry invalid:\n  " + "\n  ".join(problems))
    return reg


